"""Give the legacy dev questions every page that states their answer. No LLM.

WHY: eval_questions.json labels each question with ONE source page. Phase 2
(ERROR_ANALYSIS.md) found those labels incomplete, not wrong: when a fact is
printed on several pages (e.g. an exam table on pages 5, 6 and 30), retrieving
another copy was scored as a miss. That penalised any retriever that happened
to prefer a different copy, and it is part of why the reranker "lost" on dev.

Rule (fixed before looking at any retrieval result, deterministic):
  a page of the expected PDF is added when ALL of the question's
  expected_keywords occur within WINDOW characters of each other on it
  (case-insensitive, whitespace collapsed).
The original page is always kept. All pages are alternatives for ONE fact,
so they form a single hop: retrieving any one of them is a hit.

Keyword co-occurrence is weaker evidence than a verbatim answer quote, so
every added page is written to DEV_LABEL_ADDITIONS.md with its matching
snippet for a human to check.

Usage: python eval/expand_dev_labels.py
Output: eval/dev_questions_multipage.json, eval/DEV_LABEL_ADDITIONS.md
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

from config import PDF_DIR, page_number  # noqa: E402

SOURCE = ROOT / "eval_questions.json"
OUT_JSON = ROOT / "eval" / "dev_questions_multipage.json"
OUT_MD = ROOT / "eval" / "DEV_LABEL_ADDITIONS.md"
WINDOW = 400


def collapse(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def keyword_window(text: str, keywords: list[str]) -> str | None:
    """Return a snippet where all keywords co-occur within WINDOW chars, else None."""
    lower = text.lower()
    first = keywords[0].lower()
    for match in re.finditer(re.escape(first), lower):
        start = max(0, match.start() - WINDOW)
        window = lower[start:match.end() + WINDOW]
        if all(kw.lower() in window for kw in keywords[1:]):
            # Narrow the snippet to the span actually covering the keywords.
            positions = [window.find(kw.lower()) for kw in keywords]
            lo, hi = min(positions) + start, max(p + len(k) for p, k in zip(positions, keywords)) + start
            return text[max(0, lo - 60):hi + 60]
    return None


def load_pages(filename: str) -> dict[int, str]:
    from langchain_community.document_loaders import PyPDFLoader

    pages = {}
    for page in PyPDFLoader(str(Path(PDF_DIR) / filename)).load():
        number = page_number(page.metadata)
        if number.isdecimal():
            pages[int(number)] = collapse(page.page_content)
    return pages


def main() -> None:
    legacy = json.loads(SOURCE.read_text(encoding="utf-8"))
    cache: dict[str, dict[int, str]] = {}
    questions, additions = [], []
    for item in legacy:
        if item.get("should_refuse"):
            questions.append({"id": item["id"], "q": item["question"], "file": None, "page": None,
                              "type": "unanswerable"})
            continue
        filename, original = item["expected_source"], int(item["source_page"])
        pages = cache.setdefault(filename, load_pages(filename))
        found = {}
        for number, text in pages.items():
            snippet = keyword_window(text, item["expected_keywords"])
            if snippet:
                found[number] = snippet
        all_pages = sorted(set(found) | {original})
        added = [p for p in all_pages if p != original]
        questions.append({
            "id": item["id"], "q": item["question"], "file": filename, "page": all_pages,
            "hops": [all_pages], "type": f"legacy_{item.get('type', 'unknown')}",
            "answer": item.get("reference_answer", ""), "original_page": original,
            "pages_added": added, "label_rule": f"all expected_keywords within {WINDOW} chars",
        })
        for page in added:
            additions.append((item["id"], item["question"], item["expected_keywords"],
                              filename, original, page, found[page]))
        if original not in found:
            print(f"note: {item['id']} keywords not co-located on its own page {original}")

    OUT_JSON.write_text(json.dumps(questions, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    changed = sorted({a[0] for a in additions})
    lines = [
        "# Dev label additions (for human review)",
        "",
        f"Generated by `python eval/expand_dev_labels.py`. Rule: all expected keywords within "
        f"{WINDOW} characters on a page of the expected PDF.",
        f"{len(changed)} of {sum(1 for q in questions if q['file'])} answerable dev questions gained "
        f"{len(additions)} page(s). Delete a page from `dev_questions_multipage.json` if its snippet "
        "does not actually answer the question.",
        "",
        "| Question | Keywords | Original page | Added page | Snippet |",
        "|---|---|---|---|---|",
    ]
    for qid, question, keywords, filename, original, page, snippet in additions:
        cell = collapse(snippet).replace("|", "\\|")[:300]
        lines.append(f"| {qid}: {question} | {', '.join(keywords)} | {original} | {page} | {cell} |")
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(changed)} questions gained {len(additions)} pages: {', '.join(changed)}")
    print(f"Saved {OUT_JSON.relative_to(ROOT)} and {OUT_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
