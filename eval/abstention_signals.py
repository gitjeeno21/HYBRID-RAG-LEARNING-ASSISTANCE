"""Can a retrieval score tell answerable from unanswerable questions? (zero LLM calls)

Abstaining BEFORE the LLM (refusing when retrieval looks weak) is only safe if
some score separates the two groups. This script measures that, per question,
for the passages the live pipeline would send (hybrid RRF, top k):

  top_cosine    best dense cosine similarity among the passages
  mean_cosine   mean dense cosine over the passages that have one
  ce_top        best cross-encoder (ms-marco-MiniLM-L-6-v2) score over them

For each signal it reports ROC-AUC (probability a random answerable question
scores higher than a random unanswerable one; 0.5 = useless, 1.0 = perfect)
and the best achievable trade-off: at the threshold that keeps every
answerable question, how many unanswerable ones would be refused.

Usage: python eval/abstention_signals.py
Output: eval/ABSTENTION_SIGNALS.md, eval/abstention_signals.json
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "eval"))
os.environ["PYTHON_DOTENV_DISABLED"] = "1"

import run_eval as H  # noqa: E402  (blocks groq: this script cannot spend quota)
import config  # noqa: E402
from hybrid import hybrid_search_with_scores, unique_chunks  # noqa: E402

SETS = {"test (held-out v2)": H.EVAL_DIR / "heldout_v2_questions.json",
        "dev (legacy)": H.EVAL_DIR / "dev_questions_multipage.json"}
OUT_MD = H.EVAL_DIR / "ABSTENTION_SIGNALS.md"
OUT_JSON = H.EVAL_DIR / "abstention_signals.json"
SIGNALS = ("top_cosine", "mean_cosine", "ce_top")


def roc_auc(positive: list[float], negative: list[float]) -> float:
    """Mann-Whitney AUC with ties counted as half."""
    wins = sum((p > n) + 0.5 * (p == n) for p in positive for n in negative)
    return wins / (len(positive) * len(negative))


def refusals_at_full_recall(positive: list[float], negative: list[float]) -> int:
    """Unanswerable questions refused by the strictest cut-off that refuses NO answerable one."""
    cutoff = min(positive)
    return sum(n < cutoff for n in negative)


def main() -> None:
    from sentence_transformers import CrossEncoder

    cross_encoder = CrossEncoder(H.RERANKER_MODEL)
    files = H.corpus_files(None)
    chunks = H.make_chunks(H.load_pages(files), H.IndexSettings())
    store, _ = H.get_store(chunks, files, H.IndexSettings())
    bm25 = H.build_bm25(chunks)

    results = {}
    for name, path in SETS.items():
        rows = []
        for q in H.load_questions(path):
            pairs = unique_chunks(hybrid_search_with_scores(q["q"], store, bm25, chunks,
                                                            n_results=config.TOP_K))
            cosines = [score for _, score in pairs if score is not None]
            ce = cross_encoder.predict([(q["q"], doc.page_content) for doc, _ in pairs],
                                       show_progress_bar=False)
            rows.append({"id": q["id"], "answerable": q["type"] != "unanswerable",
                         "top_cosine": max(cosines) if cosines else 0.0,
                         "mean_cosine": sum(cosines) / len(cosines) if cosines else 0.0,
                         "ce_top": float(max(ce))})
        summary = {}
        for signal in SIGNALS:
            pos = [r[signal] for r in rows if r["answerable"]]
            neg = [r[signal] for r in rows if not r["answerable"]]
            summary[signal] = {
                "auc": round(roc_auc(pos, neg), 3),
                "answerable_min": round(min(pos), 3), "unanswerable_max": round(max(neg), 3),
                "refused_unanswerable_at_full_recall": refusals_at_full_recall(pos, neg),
                "n_answerable": len(pos), "n_unanswerable": len(neg),
            }
        results[name] = {"summary": summary, "rows": rows}

    OUT_JSON.write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
    lines = ["# Abstention signals (zero LLM calls)", "",
             "Generated by `python eval/abstention_signals.py`. Passages: the live pipeline's top "
             f"{config.TOP_K} (hybrid RRF). AUC = probability that a random answerable question "
             "scores higher than a random unanswerable one (0.5 = no separation).", "",
             "| Set | Signal | ROC-AUC | Lowest answerable | Highest unanswerable | "
             "Unanswerable refused if no answerable may be refused |", "|---|---|---|---|---|---|"]
    for name, block in results.items():
        for signal, s in block["summary"].items():
            lines.append(f"| {name} | {signal} | {s['auc']:.3f} | {s['answerable_min']:.3f} | "
                         f"{s['unanswerable_max']:.3f} | {s['refused_unanswerable_at_full_recall']}"
                         f"/{s['n_unanswerable']} |")
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
